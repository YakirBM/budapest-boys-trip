import { writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";

/**
 * Emits public/sw-manifest.js: precache list + build id (docs/07).
 * Run before `next build` so Next/Vercel collect the generated public asset.
 */

const root = process.cwd();
let sourceRevision = process.env.VERCEL_GIT_COMMIT_SHA ?? process.env.GITHUB_SHA;
if (!sourceRevision) {
  try {
    sourceRevision = execFileSync("git", ["rev-parse", "--verify", "HEAD"], {
      cwd: root,
      encoding: "utf8",
    }).trim();
  } catch {
    sourceRevision = `local-${Date.now()}`;
  }
}
const buildId = sourceRevision.slice(0, 16);

const shellUrls = [
  "/offline",
  "/manifest.webmanifest",
  "/icons/icon-192.png",
  "/icons/icon-512.png",
  "/icons/maskable-512.png",
  "/icons/apple-touch-icon.png",
];

const content = `// Generated by scripts/build-sw-manifest.mjs — do not edit.
self.BUILD_VERSION = ${JSON.stringify(buildId)};
self.PRECACHE_URLS = ${JSON.stringify(shellUrls)};
`;

writeFileSync(resolve(root, "public/sw-manifest.js"), content);
console.log(`sw-manifest.js written (build ${buildId}, ${shellUrls.length} precache entries)`);
