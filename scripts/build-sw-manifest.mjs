import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

/**
 * Emits public/sw-manifest.js: precache list + build id (docs/07).
 * Run after `next build` (postbuild) so the .next build id exists.
 */

const root = process.cwd();
const buildIdPath = resolve(root, ".next/BUILD_ID");
const buildId = existsSync(buildIdPath) ? readFileSync(buildIdPath, "utf8").trim() : `dev-${Date.now()}`;

const shellUrls = [
  "/today",
  "/offline",
  "/manifest.webmanifest",
  "/icons/icon-192.png",
  "/icons/icon-512.png",
  "/icons/maskable-512.png",
  "/icons/apple-touch-icon.png",
];

const content = `// Generated by scripts/build-sw-manifest.mjs — do not edit.
self.BUILD_VERSION = ${JSON.stringify(buildId)};
self.PRECACHE_URLS = ${JSON.stringify(shellUrls)};
`;

writeFileSync(resolve(root, "public/sw-manifest.js"), content);
console.log(`sw-manifest.js written (build ${buildId}, ${shellUrls.length} precache entries)`);
